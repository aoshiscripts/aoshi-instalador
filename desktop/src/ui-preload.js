// Ponte entre a barra (ui.html) e o processo principal.
'use strict';
const { contextBridge, ipcRenderer } = require('electron');
// <browser-action-list>: botões das extensões na barra
try { require('electron-chrome-extensions/browser-action').injectBrowserAction(); } catch (e) { console.warn('[extensões]', e && e.message); }
contextBridge.exposeInMainWorld('aoshi', {
  on: fn => ipcRenderer.on('ui', (_, ch, data) => fn(ch, data)),
  newTab: (profileId, url) => ipcRenderer.invoke('tab:new', profileId, url),
  linkOpen: pid => ipcRenderer.invoke('link:open', pid),
  usList: () => ipcRenderer.invoke('us:list'),
  usPrepare: src => ipcRenderer.invoke('us:prepare', src),
  usCommit: id => ipcRenderer.invoke('us:commit', id),
  usToggle: (id, on) => ipcRenderer.invoke('us:toggle', id, on),
  usRemove: id => ipcRenderer.invoke('us:remove', id),
  usCode: id => ipcRenderer.invoke('us:code', id),
  usSaveCode: (id, code) => ipcRenderer.invoke('us:save-code', id, code),
  usUpdate: id => ipcRenderer.invoke('us:update', id),
  linkRemove: pid => ipcRenderer.invoke('link:remove', pid),
  closeTab: id => ipcRenderer.invoke('tab:close', id),
  renameTab: (id, name) => ipcRenderer.invoke('tab:rename', id, name),
  tabMenu: id => ipcRenderer.invoke('tab:menu', id),
  activate: id => ipcRenderer.invoke('tab:activate', id),
  setProfile: (id, profileId) => ipcRenderer.invoke('tab:profile', id, profileId),
  nav: (id, what, arg) => ipcRenderer.invoke('tab:nav', id, what, arg),
  saveProfiles: list => ipcRenderer.invoke('profiles:save', list),
  testProfile: p => ipcRenderer.invoke('profiles:test', p),
  setToken: t => ipcRenderer.invoke('token:set', t),
  checkCode: () => ipcRenderer.invoke('code:check'),
  reloadAll: () => ipcRenderer.invoke('tabs:reload-all'),
  installUpdate: () => ipcRenderer.invoke('app:update-install'),
  version: () => ipcRenderer.invoke('app:version'),
  modal: on => ipcRenderer.invoke('ui:modal', on),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: s => ipcRenderer.invoke('settings:save', s),
  resetSettings: () => ipcRenderer.invoke('settings:reset'),
  clearData: o => ipcRenderer.invoke('data:clear', o),
  pickDownloads: () => ipcRenderer.invoke('downloads:pick'),
  openDownloads: f => ipcRenderer.invoke('downloads:open', f),
  clearToken: () => ipcRenderer.invoke('token:clear'),
  checkAppUpdate: () => ipcRenderer.invoke('app:check-update'),
  openReleases: () => ipcRenderer.invoke('app:open-releases'),
  extList: () => ipcRenderer.invoke('ext:list'),
  extStore: () => ipcRenderer.invoke('ext:store'),
  extRemove: id => ipcRenderer.invoke('ext:remove', id),
  extLoadFolder: () => ipcRenderer.invoke('ext:load-folder')
});
